// Helper to get nested key like 'nav.brand'
export function getT(lang, key) {
  const keys = key.split('.')
  let result = translations[lang] || translations.en
  for (const k of keys) {
    result = result?.[k]
    if (result === undefined) {
      // fallback to English
      let fb = translations.en
      for (const fk of keys) fb = fb?.[fk]
      return fb || key
    }
  }
  return result || key
}

